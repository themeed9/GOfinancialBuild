/**
 * Generates src/theme/tokens.generated.ts from the shared design tokens
 * in ../tokens, so the web app and the mobile app use one source of truth.
 *
 * Colours come from tokens/design-tokens.css, which the web generator has
 * already resolved (references, interpolated tones, dark theme).
 * Typography, spacing and radii come from design-tokens.tokens.json.
 *
 * Usage: npm run generate-theme   (re-run after editing ../tokens)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokensDir = join(here, '..', '..', 'tokens');
const outFile = join(here, '..', 'src', 'theme', 'tokens.generated.ts');

const css = readFileSync(join(tokensDir, 'design-tokens.css'), 'utf8');
const json = JSON.parse(readFileSync(join(tokensDir, 'design-tokens.tokens.json'), 'utf8'));

function block(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`Selector ${selector} not found in design-tokens.css`);
  return css.slice(start, css.indexOf('}', start));
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function colors(selector) {
  const out = {};
  for (const [, name, value] of block(selector).matchAll(/--color-([a-z0-9-]+):\s*([^;]+);/g)) {
    out[camel(name)] = value.trim();
  }
  return out;
}

const light = colors(':root');
const dark = { ...light, ...colors('[data-theme="dark"]') };

const typography = {};
for (const [role, sizes] of Object.entries(json.typography.styles)) {
  for (const [size, s] of Object.entries(sizes)) {
    typography[camel(`${role}-${size}`)] = {
      fontSize: s.fontSizePx,
      lineHeight: s.lineHeightPx,
      fontWeight: String(s.fontWeight),
      letterSpacing: Number((parseFloat(s.letterSpacing) * s.fontSizePx).toFixed(2)),
    };
  }
}

const radius = { ...json.borderRadius };

const output = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-theme.mjs from ../tokens. DO NOT EDIT.

export const lightColors = ${JSON.stringify(light, null, 2)} as const;

export const darkColors: Record<keyof typeof lightColors, string> = ${JSON.stringify(dark, null, 2)};

export const typography = ${JSON.stringify(typography, null, 2)} as const;

export const spacing = ${JSON.stringify(json.spacing.scale, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const fontFamily = ${JSON.stringify(json.typography.fontFamily)};
`;

writeFileSync(outFile, output);
console.log(`Wrote ${outFile} (${Object.keys(light).length} colours, ${Object.keys(typography).length} text styles)`);
